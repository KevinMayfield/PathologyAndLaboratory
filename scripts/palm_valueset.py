"""Write the PaLM Requestable Tests value set with its codes listed.

    python3 scripts/palm_valueset.py

The SNOMED CT UK Edition refset 1853561000000109 (Pathology and laboratory medicine procedure
simple reference set) is not in the UK Edition tx.fhir.org holds, so a refset filter cannot be
expanded when the IG is built. This script expands the refset on CSIRO's public Ontoserver
(which holds a recent UK Edition) and writes every member as an explicit code to
input/fsh/Terminology/PaLMProcedure.fsh. Re-run it for a new UK Edition release.
"""

import json
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "input" / "fsh" / "Terminology" / "PaLMProcedure.fsh"
SERVER = "https://tx.ontoserver.csiro.au/fhir"
REFSET = "1853561000000109"
UK_EDITION = "http://snomed.info/sct/83821000000107"


def expand():
    query = urllib.parse.urlencode({"url": f"{UK_EDITION}?fhir_vs=refset/{REFSET}", "count": 10000})
    request = urllib.request.Request(f"{SERVER}/ValueSet/$expand?{query}", headers={"Accept": "application/fhir+json"})
    with urllib.request.urlopen(request, timeout=120) as response:
        expansion = json.load(response)["expansion"]
    version = next(p["valueUri"] for p in expansion.get("parameter", []) if p["name"] == "version")
    return sorted(expansion["contains"], key=lambda c: c["display"].lower()), version


def main():
    concepts, version = expand()
    release = version.rsplit("/", 1)[-1]
    lines = [
        "// GENERATED by scripts/palm_valueset.py - do not edit. The members of the SNOMED CT UK Edition",
        f"// refset {REFSET} (Pathology and laboratory medicine procedure simple reference set), expanded",
        f"// on {SERVER} from {version}.",
        "",
        "Alias: $sct = http://snomed.info/sct",
        "",
        "ValueSet:       PaLMProcedure",
        "Id:             palm-procedure",
        'Title:          "PaLM Requestable Tests (SNOMED CT)"',
        'Description:    """',
        "Laboratory tests that can be requested (\"requestables\") and test groups: the members of the SNOMED CT",
        f"UK Edition refset {REFSET} *Pathology and laboratory medicine procedure simple reference set* (PaLM),",
        f"UK Edition release {release} ({len(concepts)} concepts). This is the England equivalent, for pathology, of",
        "the National Genomic Test Directory (genomics) and NICIP (imaging): laboratories map their local test",
        "codes to it. Results are coded from the PaLM observables refset 1853551000000106 instead.",
        "",
        "The codes are listed (rather than given as a refset rule, as UK Core's",
        "`UKCore-PathologyAndLaboratoryMedicineProcedures` does) because the UK Edition on tx.fhir.org is older",
        "than this refset. Generated by `scripts/palm_valueset.py` from CSIRO's public Ontoserver; re-run it for a",
        "new UK Edition release.",
        '"""',
        "* ^status = #draft",
        "* ^experimental = true",
    ]
    for c in concepts:
        display = c["display"].replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'* $sct#{c["code"]} "{display}"')
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(concepts)} concepts ({version}) to {OUT}")


if __name__ == "__main__":
    main()
