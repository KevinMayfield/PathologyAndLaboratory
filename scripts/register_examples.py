"""Register the notebook outputs as examples in the Implementation Guide.

    python3 scripts/register_examples.py

Reads examples/fhir/message/*.json and examples/fhir/document/*.json (written by the
notebooks) and rewrites the generated `resources:` and `groups:` block at the end of
sushi-config.yaml, so the IG Publisher lists them as examples. The folders themselves are
loaded through the `path-resource` parameter in sushi-config.yaml.

Each example is validated against this guide's profile (exampleCanonical) - BundleMessage or
BundleLaboratoryReportDocument - rather than the NHS England profiles in the documents'
meta.profile, so the IG does not depend on the NHS England package.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "sushi-config.yaml"
BEGIN = "# BEGIN generated by scripts/register_examples.py - do not edit\n"
END = "# END generated by scripts/register_examples.py\n"

KINDS = [
    ("message", "https://examplesihe.org.uk/StructureDefinition/BundleMessage", "nhse-fhir-messages", "Example: NHS England Examples - FHIR Messages",
     "The HL7 v2 ORU^R01 versions of the NHS England Pathology FHIR IG examples converted to FHIR Messages "
     "(notebook 01-oru-r01-to-fhir-message). Practitioners and organisations are identifier references, as in HL7 v2.",
     "FHIR Message (R01) converted from the HL7 v2 ORU^R01 version of the NHS England example {name}"),
    ("document", "https://examplesihe.org.uk/StructureDefinition/BundleLaboratoryReportDocument", "nhse-fhir-documents", "Example: NHS England Examples - FHIR Documents",
     "The FHIR Messages converted to the FHIR Documents sent to the NHS England Pathology Laboratory Reporting API "
     "(notebook 02-fhir-message-to-fhir-document), with generated human readable narrative.",
     "FHIR Document for the NHS England Pathology Laboratory Reporting API, built from the FHIR Message for the NHS "
     "England example {name}, with generated narrative"),
]


def main():
    resources, groups = [], []
    for kind, canonical, group_id, group_name, group_description, description in KINDS:
        ids = []
        for path in sorted((ROOT / "examples" / "fhir" / kind).glob("*.json")):
            bundle = json.loads(path.read_text())
            ids.append(bundle["id"])
            resources.append(f"  Bundle/{bundle['id']}:\n"
                             f"    name: \"{kind.capitalize()} - {path.stem}\"\n"
                             f"    description: \"{description.format(name=path.stem)}\"\n"
                             f"    exampleCanonical: {canonical}\n")
        groups.append(f"  {group_id}:\n    name: \"{group_name}\"\n    description: \"{group_description}\"\n"
                      "    resources:\n" + "".join(f"      - Bundle/{i}\n" for i in ids))
    block = BEGIN + "resources:\n" + "".join(resources) + "groups:\n" + "".join(groups) + END
    text = CONFIG.read_text()
    if BEGIN in text:
        text = text[:text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    else:
        text = text.rstrip("\n") + "\n\n" + block
    CONFIG.write_text(text)
    print(f"registered {len(resources)} examples in {CONFIG.name}")


if __name__ == "__main__":
    main()
